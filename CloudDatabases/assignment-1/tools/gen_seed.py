#!/usr/bin/env python3
"""generates 02_data.sql (E1). only filler data is generated; the events in
03_timeline.sql are written by hand."""

from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "02_data.sql"

SENTINEL_DATE = "9999-12-31"
SENTINEL_TS = "9999-12-31 23:59:59.999999"

clubs = [
    (1, "FC Nord", "Cluj-Napoca", "Stadionul Nord", 1907),
    (2, "CS Port", "Constanta", "Arena Port", 1920),
    (3, "Universitatea Est", "Iasi", "Stadionul Est", 1945),
    (4, "Rapid Vest", "Timisoara", "Arena Vest", 1923),
    (5, "CSM Centru", "Brasov", "Stadionul Centru", 1936),
    (6, "FC Sud", "Craiova", "Arena Sud", 1948),
]

agents = [
    (1, "Nord Sports", "Nord Sports Management"),
    (2, "Port Talent", "Port Talent Group"),
    (3, "Est Football", "Est Football Agency"),
    (4, "Vest Players", "Vest Players Ltd"),
    (5, "Centru Pro", "Centru Pro Sports"),
    (6, "Sud Stars", "Sud Stars Management"),
]

coaches = [
    (1, "Mihai Rusu", "ROU"),
    (2, "Andrei Pop", "ROU"),
    (3, "Vlad Ionescu", "ROU"),
    (4, "Dan Marinescu", "ROU"),
    (5, "Sorin Dumitrescu", "ROU"),
    (6, "Radu Stan", "ROU"),
]

seasons = [
    (1, "2025/26", "2025-07-01", "2026-07-01"),
    (2, "2026/27", "2026-07-01", "2027-07-01"),
]

first_names = [
    "Alexandru",
    "Andrei",
    "Bogdan",
    "Cristian",
    "Daniel",
    "Dragos",
    "Eduard",
    "Florin",
    "Gabriel",
    "Horia",
    "Ionut",
    "Iulian",
    "Lucian",
    "Marius",
    "Mihai",
    "Nicolae",
    "Octavian",
    "Paul",
    "Radu",
    "Robert",
    "Sergiu",
    "Stefan",
    "Tiberiu",
    "Valentin",
    "Vlad",
    "Adrian",
    "Catalin",
    "Cosmin",
    "Doru",
    "Emil",
]
last_names = [
    "Albu",
    "Barbu",
    "Cernat",
    "Dobre",
    "Enache",
    "Florea",
    "Ganea",
    "Hanganu",
    "Ilie",
    "Jianu",
    "Lazar",
    "Munteanu",
    "Neagu",
    "Oprea",
    "Pavel",
    "Rusu",
    "Stoica",
    "Toma",
    "Ungureanu",
    "Varga",
    "Zamfir",
    "Balint",
    "Cretu",
    "Dumitru",
    "Fodor",
    "Grigore",
    "Hodor",
    "Ionescu",
    "Lupu",
    "Marin",
]

players = []
seen = set()
i = 0
while len(players) < 60:
    fn = first_names[i % len(first_names)]
    ln = last_names[(i * 7 + i // len(first_names)) % len(last_names)]
    name = f"{fn} {ln}"
    i += 1
    if name in seen:
        continue
    seen.add(name)
    pid = len(players) + 1
    birth = date(1995, 1, 1) + timedelta(days=(pid * 53) % 3650)
    position = ["GK", "DF", "DF", "MF", "MF", "FW"][(pid - 1) % 6]
    nationality = "ROU"
    if pid % 7 == 0:
        nationality = "SRB"
    elif pid % 11 == 0:
        nationality = "BRA"
    elif pid % 13 == 0:
        nationality = "FRA"
    players.append(
        (pid, name, birth.isoformat(), nationality, position, (pid - 1) % 6 + 1)
    )

base_salary = {"GK": 90000, "DF": 110000, "MF": 130000, "FW": 150000}
base_value = {"GK": 450000, "DF": 700000, "MF": 1100000, "FW": 1600000}

contracts = []
for p in players:
    pid, _, _, _, position, agent_id = p
    if pid > 55:
        continue
    club_id = 6 if pid >= 51 else (pid - 1) // 10 + 1
    shirt = (pid - 1) % 10 + 1
    salary = base_salary[position] + ((pid * 3500) % 80000)
    salary = round(salary / 500) * 500
    contracts.append((pid, club_id, shirt, salary, "permanent"))

values = []
for p in players:
    pid, _, _, _, position, _ = p
    value = base_value[position] + ((pid * 123456) % 4700000)
    value = round(value / 10000) * 10000
    values.append((pid, value))

lines = []
lines.append("-- author: Mihai-Cristian Farcaș")
lines.append("-- E1: initial load in one transaction, generated by tools/gen_seed.py")
lines.append("")
lines.append("USE football_bitemporal;")
lines.append("SET NAMES utf8mb4;")
lines.append("SET time_zone = '+00:00';")
lines.append("")
lines.append("-- simulated clock: every row here gets the same tx time")
lines.append("SET @sim_now := '2025-07-01 09:00:00';")
lines.append("")
lines.append("-- one tx_id for the whole load")
lines.append("INSERT INTO tx_registry (tx_id, tx_time, author, reason) VALUES")
lines.append(
    "  (1, @sim_now, 'seed', 'E1 initial load: clubs, players, contracts, values, licences, coach roles');"
)
lines.append("SET @e1_tx := 1;")
lines.append("")
lines.append("-- anchors")
lines.append("INSERT INTO agent (agent_id, full_name, agency) VALUES")
lines.append(",\n".join(f"  ({a[0]}, '{a[1]}', '{a[2]}')" for a in agents) + ";")
lines.append("")
lines.append("INSERT INTO club (club_id, name, city, stadium, founded_year) VALUES")
lines.append(
    ",\n".join(f"  ({c[0]}, '{c[1]}', '{c[2]}', '{c[3]}', {c[4]})" for c in clubs) + ";"
)
lines.append("")
lines.append("INSERT INTO coach (coach_id, full_name, nationality) VALUES")
lines.append(",\n".join(f"  ({c[0]}, '{c[1]}', '{c[2]}')" for c in coaches) + ";")
lines.append("")
lines.append("INSERT INTO season (season_id, name, start_date, end_date) VALUES")
lines.append(
    ",\n".join(f"  ({s[0]}, '{s[1]}', '{s[2]}', '{s[3]}')" for s in seasons) + ";"
)
lines.append("")
lines.append(
    "INSERT INTO player (player_id, full_name, birth_date, nationality, position, agent_id) VALUES"
)
lines.append(
    ",\n".join(
        f"  ({p[0]}, '{p[1]}', '{p[2]}', '{p[3]}', '{p[4]}', {p[5]})" for p in players
    )
    + ";"
)
lines.append("")
lines.append("-- version tables")
lines.append("INSERT INTO club_license_version")
lines.append(
    "  (club_id, league_name, license_status, valid_from, valid_to, tx_from, tx_to, tx_id) VALUES"
)
license_rows = []
for c in clubs:
    status = "conditional" if c[0] == 6 else "full"
    license_rows.append(
        f"  ({c[0]}, 'SuperLiga', '{status}', '2025-07-01', '{SENTINEL_DATE}', "
        f"@sim_now, '{SENTINEL_TS}', @e1_tx)"
    )
lines.append(",\n".join(license_rows) + ";")
lines.append("")
lines.append("INSERT INTO contract_version")
lines.append(
    "  (player_id, club_id, shirt_number, salary_eur, contract_type, valid_from, valid_to, tx_from, tx_to, tx_id) VALUES"
)
contract_rows = []
for pid, club_id, shirt, salary, ctype in contracts:
    contract_rows.append(
        f"  ({pid}, {club_id}, {shirt}, {salary}.00, '{ctype}', '2025-07-01', "
        f"'{SENTINEL_DATE}', @sim_now, '{SENTINEL_TS}', @e1_tx)"
    )
lines.append(",\n".join(contract_rows) + ";")
lines.append("")
lines.append("INSERT INTO coach_assignment_version")
lines.append(
    "  (coach_id, club_id, role_title, valid_from, valid_to, tx_from, tx_to, tx_id) VALUES"
)
coach_rows = []
for c in clubs:
    coach_rows.append(
        f"  ({c[0]}, {c[0]}, 'Head coach', '2025-07-01', '{SENTINEL_DATE}', "
        f"@sim_now, '{SENTINEL_TS}', @e1_tx)"
    )
lines.append(",\n".join(coach_rows) + ";")
lines.append("")
lines.append("INSERT INTO player_value_version")
lines.append(
    "  (player_id, market_value_eur, valid_from, valid_to, tx_from, tx_to, tx_id) VALUES"
)
value_rows = []
for pid, value in values:
    value_rows.append(
        f"  ({pid}, {value}.00, '2025-07-01', '{SENTINEL_DATE}', @sim_now, '{SENTINEL_TS}', @e1_tx)"
    )
lines.append(",\n".join(value_rows) + ";")
lines.append("")
lines.append("-- story index")
lines.append("INSERT INTO story_event")
lines.append(
    "  (tx_id, event_code, table_name, business_key, valid_date, old_value, new_value, note) VALUES"
)
lines.append(
    "  (@e1_tx, 'E1', 'all', 'league', '2025-07-01', NULL, '6 clubs / 60 players / 55 contracts', "
    "'Initial load; all rows share tx_id 1');"
)
lines.append("")

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT} ({len(lines)} lines)")
